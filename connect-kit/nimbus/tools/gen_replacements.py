#!/usr/bin/env python3
"""Generate patches/http/src/replacements.s from hosts.conf.

Every `rs_map target, replacement` becomes one find_and_replace call in the
http:C patch, and the target/replacement strings are emitted into the literal
pool of main.s.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def parse(path):
    host = None
    maps = []
    with open(path) as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if parts[0] == "RS_HOST":
                host = parts[1]
                continue
            if len(parts) == 2:
                maps.append((parts[0], f"{host}:{parts[1]}"))
    return host, maps


def main():
    host, maps = parse(os.path.join(ROOT, "hosts.conf"))
    if not host:
        sys.exit("hosts.conf: missing RS_HOST")
    code = ["; AUTO-GENERATED by tools/gen_replacements.py - do not edit.",
            f"; RS_HOST = {host}  ({len(maps)} hosts)", ""]
    for i, (target, repl) in enumerate(maps):
        code += [
            f"\tldr     r3, =tgt{i}",
            "\tstr     r3, [r11, #-0x8]",
            f"\tldr     r3, =rep{i}",
            "\tstr     r3, [r11, #-0x14]",
            "\tldr     r2, [r11, #-0x14]",
            "\tldr     r1, [r11, #-0x8]",
            "\tldr     r0, [r11, #-0x28]",
            "\tbl      find_and_replace",
        ]
    code.append("")
    strings = ["; AUTO-GENERATED by tools/gen_replacements.py - do not edit.",
               "; data emitted after the code so it stays word-aligned.", ""]
    for i, (target, repl) in enumerate(maps):
        strings.append(f"tgt{i}:\n\t.asciiz \"{target}\"")
        strings.append(f"rep{i}:\n\t.asciiz \"{repl}\"")
    src = os.path.join(ROOT, "patches", "http", "src")
    with open(os.path.join(src, "replacements.s"), "w") as fh:
        fh.write("\n".join(code) + "\n")
    with open(os.path.join(src, "strings.s"), "w") as fh:
        fh.write("\n".join(strings) + "\n")
    print(f"wrote replacements.s + strings.s ({len(maps)} mappings -> {host})")


if __name__ == "__main__":
    main()
